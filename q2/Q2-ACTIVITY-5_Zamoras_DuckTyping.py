# 1. What do all the methods (move(), special_move(), use()) in the previous activities have in common?

# All three methods demonstrate polymorphism because they have the same method name across different classes but perform different actions depending on the object that calls them.

# 2. How does this activity show polymorphism in a gaming context?

# It shows polymorphism by allowing different game characters and items to perform different actions through the same method. For example, different characters can execute their own special moves, while different potions produce different effects when used.

# 3. Can you think of other examples where the same action behaves differently depending on the character or item?

# Yes. An attack action can behave differently depending on the character. A warrior may perform a sword strike, a mage may cast a spell, and an archer may shoot an arrow. Similarly, equipping different weapons can change how a character attacks.